// `npm run dev`: start the Worker locally with Wrangler, using the right config WITHOUT touching anyone's files.
//
// Why: the committed wrangler.toml is a placeholder that includes the [ai] binding (Workers AI). `wrangler dev` sends AI calls to
// Cloudflare's real service (and may be charged), so for local work we leave that block out. Which config is used:
//   1. WRANGLER_CONFIG, if you set it;
//   2. wrangler.local.toml, if you have one (git-ignored: your own local settings);
//   3. otherwise wrangler.generated.toml, written here from wrangler.toml with the [ai] block removed (git-ignored).
// wrangler.toml itself is never modified.
//
//   npm run dev -- --port 8788                           start the Worker (extra arguments go to wrangler dev)
//   node scripts/dev.mjs --wrangler d1 execute DB --local --file=./schema.sql
//                                                        run any other wrangler command with the SAME config (npm run db:init:local does this),
//                                                        so local commands and `npm run dev` always share one local database
//
// Local D1 state is keyed by the database_id in the config used, so mixing configs would give you two different local databases.
import { spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Removes the [ai] table (and the lines under it) from a wrangler.toml text. */
export function withoutAiBlock(text) {
  const out = [];
  let skipping = false;
  for (const line of String(text).split(/\r?\n/)) {
    if (/^\s*\[ai\]\s*$/.test(line)) { skipping = true; continue; }
    if (skipping) { if (/^\s*\[/.test(line)) skipping = false; else continue; }
    out.push(line);
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n");
}

/** True if a config text still declares the [ai] binding. */
export function hasAiBlock(text) { return /^\s*\[ai\]\s*$/m.test(String(text)); }

export function pickConfig(env = process.env, root = ROOT) {
  const own = (p, why) => {
    const abs = isAbsolute(p) ? p : join(root, p);
    const ai = existsSync(abs) && hasAiBlock(readFileSync(abs, "utf8"));
    return { path: p, why, warnAi: ai };
  };
  if (env.WRANGLER_CONFIG) return own(env.WRANGLER_CONFIG, "WRANGLER_CONFIG");
  if (existsSync(join(root, "wrangler.local.toml"))) return own("wrangler.local.toml", "your wrangler.local.toml");
  const base = join(root, "wrangler.toml");
  if (!existsSync(base)) throw new Error("No wrangler.toml found in " + root);
  writeFileSync(join(root, "wrangler.generated.toml"),
    "# Generated by `npm run dev` from wrangler.toml with the [ai] block removed. Git-ignored; safe to delete.\n" + withoutAiBlock(readFileSync(base, "utf8")));
  return { path: "wrangler.generated.toml", why: "wrangler.toml without the [ai] block, so local runs never call the real Workers AI", warnAi: false };
}

/** Command to run wrangler without a shell (so arguments with spaces survive and the process can be stopped cleanly). */
export function wranglerCommand(root = ROOT) {
  const bin = join(root, "node_modules", "wrangler", "bin", "wrangler.js");
  return existsSync(bin) ? { cmd: process.execPath, prefix: [bin], shell: false } : { cmd: "npx", prefix: ["wrangler"], shell: process.platform === "win32" };
}

if (process.argv[1] && /[\\/]dev\.mjs$/.test(process.argv[1])) {
  const argv = process.argv.slice(2);
  const raw = argv[0] === "--wrangler";
  const { path, why, warnAi } = pickConfig();
  const args = raw ? argv.slice(1) : ["dev", ...argv];
  console.log(`${raw ? "Running wrangler" : "Starting the Worker locally"} with ${path} (${why}).`);
  if (warnAi) console.warn(`Note: ${path} still has an [ai] block, so Workers AI calls go to Cloudflare's real service from this machine (and may be charged). Remove that block from your local config to stay fully local.`);
  const { cmd, prefix, shell } = wranglerCommand();
  const child = spawn(cmd, [...prefix, ...args, "-c", path], { cwd: ROOT, stdio: "inherit", shell });
  child.on("exit", (code) => process.exit(code ?? 0));
  for (const sig of ["SIGINT", "SIGTERM"]) process.on(sig, () => child.kill(sig));
}
